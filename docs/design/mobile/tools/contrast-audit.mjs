#!/usr/bin/env node
/**
 * Contrast audit for docs/design/mobile/02-design-tokens.json
 *
 * Checks every colour pair the app actually renders and reports the ratio
 * against the WCAG 2.2 AA thresholds declared in the token file's `a11y`
 * section. Run after any token change:
 *
 *   node docs/design/mobile/tools/contrast-audit.mjs
 *
 * Exits non-zero if any pair fails, so it can be wired into CI later.
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, '..', '02-design-tokens.json'), 'utf8'));

const hex = (h) => {
  const s = h.replace('#', '');
  const v = s.length === 3 ? s.split('').map((c) => c + c).join('') : s;
  return [0, 2, 4].map((i) => parseInt(v.slice(i, i + 2), 16));
};

const channel = (c) => {
  const s = c / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};

const luminance = (h) => {
  const [r, g, b] = hex(h);
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
};

const ratio = (a, b) => {
  const [l1, l2] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (l1 + 0.05) / (l2 + 0.05);
};

/** Pair definitions: [label, fg, bg, thresholdKey] */
const pairs = [];
const add = (label, fg, bg, kind = 'bodyText') => pairs.push({ label, fg, bg, kind });

const push = (mode) => {
  const c = tokens.color[mode];
  const onRoles = [
    ['primary', 'onPrimary'], ['primaryContainer', 'onPrimaryContainer'],
    ['secondary', 'onSecondary'], ['secondaryContainer', 'onSecondaryContainer'],
    ['tertiary', 'onTertiary'], ['tertiaryContainer', 'onTertiaryContainer'],
    ['error', 'onError'], ['errorContainer', 'onErrorContainer'],
    ['surfaceContainerLowest', 'onSurface'], ['surfaceContainerLow', 'onSurface'],
    ['surfaceContainer', 'onSurface'], ['surfaceContainerHigh', 'onSurface'],
    ['surface', 'onSurfaceVariant'], ['surfaceContainerLowest', 'onSurfaceSubtle'],
    ['inverseSurface', 'inverseOnSurface']
  ];
  for (const [bg, fg] of onRoles) add(`${mode}: ${fg} on ${bg}`, c[fg], c[bg]);
  add(`${mode}: primary vs surface (UI)`, c.primary, c.surfaceContainerLowest, 'uiComponent');
  add(`${mode}: outline vs surface (UI)`, c.outline, c.surfaceContainerLowest, 'uiComponent');
  add(`${mode}: error vs surface (UI)`, c.error, c.surfaceContainerLowest, 'uiComponent');
  const danger = tokens.domain.status.danger;
  add(
    `${mode}: danger fg on danger bg`,
    mode === 'dark' ? danger.darkFg : danger.fg,
    mode === 'dark' ? danger.darkBg : danger.bg
  );
  add(`${mode}: onSurface on pageBackground`, c.onSurface, c.pageBackground);
};
push('light');
push('dark');

// Domain status pairs use their own light/dark values.
// Keys beginning with `$` are token-file metadata, not statuses.
for (const [key, s] of Object.entries(tokens.domain.status)) {
  if (key.startsWith('$') || typeof s !== 'object' || !s.fg) continue;
  add(`status.${key} (light)`, s.fg, s.bg);
  add(`status.${key} (dark)`, s.darkFg, s.darkBg);
}

const results = pairs.map((p) => {
  const r = ratio(p.fg, p.bg);
  const need = tokens.a11y.contrast[p.kind];
  return { ...p, ratio: Math.round(r * 100) / 100, need, pass: r >= need };
});

const width = Math.max(...results.map((r) => r.label.length));
const lines = [
  '| Pair | Ratio | Required | Result |',
  '|---|---:|---:|:--:|',
  ...results.map(
    (r) =>
      `| ${r.label} | ${r.ratio.toFixed(2)}:1 | ${r.need}:1 | ${r.pass ? '✅' : '❌'} |`
  )
];

const failures = results.filter((r) => !r.pass);
console.log(lines.join('\n'));
console.log(
  `\n${results.length - failures.length}/${results.length} pairs pass. ` +
    (failures.length ? `${failures.length} failing.` : 'No failures.')
);

if (process.argv.includes('--markdown')) {
  const header = [
    '# Contrast audit — RetailOps Android tokens',
    '',
    'Generated by `tools/contrast-audit.mjs` from `02-design-tokens.json`.',
    'Thresholds: body text 4.5:1, large text 3:1, UI component 3:1 (WCAG 2.2 AA).',
    '',
    '> Re-run this after any token edit. A failing pair is a design bug, not a rounding error.',
    ''
  ].join('\n');
  console.log(`\n---MARKDOWN---\n${header}\n${lines.join('\n')}\n`);
}

process.exit(failures.length ? 1 : 0);
