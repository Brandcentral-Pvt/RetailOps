    'plug-connected-20-filled',
    'checkmark-square-20-filled',
    'arrow-counterclockwise-20-filled',
    'chevron-right-20-filled',
    'chevron-left-20-filled',
    'chevron-down-20-filled',
    'sign-out-20-filled',
